
package com.servicedesk.servicedesk_backend.exception;

// STEP 1: IMPORT REQUIRED CLASSES

import com.servicedesk.servicedesk_backend.category.exception.CategoryAlreadyExistsException;
import com.servicedesk.servicedesk_backend.category.exception.ResourceNotFoundException;
import jakarta.servlet.http.HttpServletRequest;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import org.springframework.dao.DataIntegrityViolationException;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.http.converter.HttpMessageNotReadableException;

import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.core.AuthenticationException;

import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.Map;


// STEP 2: DECLARE GLOBAL EXCEPTION HANDLER

// @RestControllerAdvice allows this class to handle exceptions
// thrown by multiple REST controllers.
@RestControllerAdvice
public class GlobalExceptionHandler {

    // STEP 3: CREATE LOGGER

    // Used to record unexpected errors in the application logs.
    private static final Logger logger =
            LoggerFactory.getLogger(GlobalExceptionHandler.class);


    // STEP 4: HANDLE REQUEST VALIDATION ERRORS

    // Handles errors generated by @Valid annotations.
    //
    // Example:
    // Empty name, invalid email or short password.
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<ApiError> handleValidationException(
            MethodArgumentNotValidException exception,
            HttpServletRequest request) {

        // STEP 4.1: CREATE MAP FOR FIELD ERRORS

        // Store each invalid field and its corresponding error message.
        Map<String, String> validationErrors = new LinkedHashMap<>();

        // STEP 4.2: EXTRACT VALIDATION ERRORS

        exception.getBindingResult()
                .getFieldErrors()
                .forEach(fieldError -> {

                    // Keep the first validation message for each field.
                    validationErrors.putIfAbsent(
                            fieldError.getField(),
                            fieldError.getDefaultMessage() != null
                                    ? fieldError.getDefaultMessage()
                                    : "Invalid value"
                    );
                });

        // STEP 4.3: RETURN BAD REQUEST RESPONSE

        ApiError apiError = new ApiError(
                Instant.now(),
                HttpStatus.BAD_REQUEST.value(),
                HttpStatus.BAD_REQUEST.getReasonPhrase(),
                "Request validation failed",
                request.getRequestURI(),
                validationErrors
        );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(apiError);
    }


    // STEP 5: HANDLE INVALID JSON REQUEST

    // Handles malformed JSON or JSON that cannot be
    // converted into the expected request DTO.
    @ExceptionHandler(HttpMessageNotReadableException.class)
    public ResponseEntity<ApiError> handleInvalidJson(
            HttpMessageNotReadableException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.BAD_REQUEST,
                "Invalid or malformed JSON request",
                request
        );
    }


    // STEP 6: HANDLE DUPLICATE EMAIL REGISTRATION

    // Handles our custom EmailAlreadyExistsException.
    @ExceptionHandler(EmailAlreadyExistsException.class)
    public ResponseEntity<ApiError> handleDuplicateEmail(
            EmailAlreadyExistsException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.CONFLICT,
                exception.getMessage(),
                request
        );
    }


    // STEP 7: HANDLE DATABASE CONSTRAINT VIOLATIONS

    // Handles database-level constraint violations.
    // For example, duplicate email caused by simultaneous requests.
    @ExceptionHandler(DataIntegrityViolationException.class)
    public ResponseEntity<ApiError> handleDatabaseConstraintViolation(
            DataIntegrityViolationException exception,
            HttpServletRequest request) {

        logger.warn(
                "Database constraint violation on {}",
                request.getRequestURI()
        );

        return buildErrorResponse(
                HttpStatus.CONFLICT,
                "A record with the supplied details already exists or violates a database constraint",
                request
        );
    }


    // STEP 8: HANDLE AUTHENTICATION ERRORS

    // Handles incorrect login credentials and other
    // authentication failures raised inside controller/service execution.
    @ExceptionHandler(AuthenticationException.class)
    public ResponseEntity<ApiError> handleAuthenticationException(
            AuthenticationException exception,
            HttpServletRequest request) {

        // Don't reveal whether the email or password was incorrect.
        return buildErrorResponse(
                HttpStatus.UNAUTHORIZED,
                "Invalid email or password",
                request
        );
    }


    // STEP 9: HANDLE ILLEGAL ARGUMENT ERRORS

    // Handles invalid arguments that reach the application layer.
    @ExceptionHandler(IllegalArgumentException.class)
    public ResponseEntity<ApiError> handleIllegalArgument(
            IllegalArgumentException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.BAD_REQUEST,
                exception.getMessage(),
                request
        );
    }


    // STEP 10: HANDLE ACCESS DENIED ERRORS

    // Handles access-denied exceptions raised during controller execution.
    @ExceptionHandler(AccessDeniedException.class)
    public ResponseEntity<ApiError> handleAccessDenied(
            AccessDeniedException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.FORBIDDEN,
                "You do not have permission to access this resource",
                request
        );
    }


    // STEP 11: HANDLE UNEXPECTED EXCEPTIONS

    // This catches unexpected exceptions that aren't handled
    // by the more specific exception handlers above.
    @ExceptionHandler(Exception.class)
    public ResponseEntity<ApiError> handleUnexpectedException(
            Exception exception,
            HttpServletRequest request) {

        // Log the complete exception for developer debugging.
        logger.error(
                "Unexpected error on {} {}",
                request.getMethod(),
                request.getRequestURI(),
                exception
        );

        // Never expose internal stack traces or database details
        // in the API response.
        return buildErrorResponse(
                HttpStatus.INTERNAL_SERVER_ERROR,
                "An unexpected error occurred",
                request
        );
    }


    // STEP 12: CREATE REUSABLE ERROR RESPONSE METHOD

    // This method avoids repeating ApiError construction
    // inside every exception handler.
    private ResponseEntity<ApiError> buildErrorResponse(
            HttpStatus status,
            String message,
            HttpServletRequest request) {

        ApiError apiError = new ApiError(
                Instant.now(),
                status.value(),
                status.getReasonPhrase(),
                message,
                request.getRequestURI(),
                Map.of()
        );

        return ResponseEntity
                .status(status)
                .body(apiError);
    }
    // STEP 13: HANDLE CATEGORY DUPLICATE ERROR

    @ExceptionHandler(CategoryAlreadyExistsException.class)
    public ResponseEntity<ApiError> handleCategoryAlreadyExists(
            CategoryAlreadyExistsException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.CONFLICT,
                exception.getMessage(),
                request
        );
    }


// STEP 14: HANDLE RESOURCE NOT FOUND ERROR

    @ExceptionHandler(ResourceNotFoundException.class)
    public ResponseEntity<ApiError> handleResourceNotFound(
            ResourceNotFoundException exception,
            HttpServletRequest request) {

        return buildErrorResponse(
                HttpStatus.NOT_FOUND,
                exception.getMessage(),
                request
        );
    }
}
